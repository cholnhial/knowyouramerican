package com.knowyouramerican.idiom;

import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.sql.Connection;
import java.sql.PreparedStatement;
import org.flywaydb.core.api.MigrationVersion;
import org.flywaydb.core.api.migration.Context;
import org.flywaydb.core.api.migration.JavaMigration;
import org.springframework.aot.hint.RuntimeHints;
import org.springframework.aot.hint.RuntimeHintsRegistrar;
import org.springframework.context.annotation.ImportRuntimeHints;
import org.springframework.core.io.ClassPathResource;
import org.springframework.stereotype.Component;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;

/**
 * V3: loads {@code db/seed/idioms.jsonl} (generated by tools/idiom-extractor) into {@code idiom}.
 *
 * <p>Registered as a Spring bean, which Spring Boot hands to Flyway, so no classpath scanning
 * is needed (native-image friendly). Uses Jackson's tree model, so no reflection either.
 *
 * <p>Runs once. To ship a corrected seed later, add a new migration (e.g. V5) that updates rows
 * by headword; never re-run this one, because questions reference idiom ids.
 */
@Component
@ImportRuntimeHints(IdiomSeedMigration.Hints.class)
public class IdiomSeedMigration implements JavaMigration {

    static final String SEED = "db/seed/idioms.jsonl";

    private final JsonMapper json;

    public IdiomSeedMigration(JsonMapper json) {
        this.json = json;
    }

    @Override
    public MigrationVersion getVersion() {
        return MigrationVersion.fromVersion("3");
    }

    @Override
    public String getDescription() {
        return "seed idioms";
    }

    /** No checksum: the seed is loaded once; later corrections ship as new migrations. */
    @Override
    public Integer getChecksum() {
        return null;
    }

    @Override
    public boolean canExecuteInTransaction() {
        return true;
    }

    @Override
    public void migrate(Context context) throws Exception {
        Connection conn = context.getConnection();
        String sql = """
                INSERT INTO idiom (headword, alt_forms, definition, notes, examples_json,
                                   senses_json, fun_score, source_page)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?)""";
        int count = 0;
        try (var in = new ClassPathResource(SEED).getInputStream();
             var reader = new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8));
             PreparedStatement ps = conn.prepareStatement(sql)) {
            String line;
            while ((line = reader.readLine()) != null) {
                if (line.isBlank()) continue;
                JsonNode idiom = json.readTree(line);
                JsonNode senses = idiom.get("senses");
                JsonNode primary = primarySense(senses);

                ps.setString(1, idiom.get("headword").asString());
                ps.setString(2, json.writeValueAsString(idiom.get("altForms")));
                ps.setString(3, primary.get("definition").asString());
                JsonNode notes = primary.get("notes");
                ps.setString(4, notes == null || notes.isNull() ? null : notes.asString());
                ps.setString(5, json.writeValueAsString(primary.get("examples")));
                ps.setString(6, json.writeValueAsString(senses));
                ps.setInt(7, idiom.get("funScore").asInt());
                ps.setInt(8, idiom.get("page").asInt());
                ps.addBatch();
                if (++count % 500 == 0) ps.executeBatch();
            }
            ps.executeBatch();
        }
        if (count == 0) {
            throw new IllegalStateException(SEED + " is empty — run `make extract`");
        }
    }

    /** The sense questions are built from: the first one that has example sentences. */
    static JsonNode primarySense(JsonNode senses) {
        for (JsonNode s : senses) {
            if (!s.get("examples").isEmpty()) return s;
        }
        return senses.get(0);
    }

    static class Hints implements RuntimeHintsRegistrar {
        @Override
        public void registerHints(RuntimeHints hints, ClassLoader classLoader) {
            hints.resources().registerPattern(SEED);
        }
    }
}
